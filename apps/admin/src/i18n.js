export const useT = (lang) => (key) => {
  const keys = key.split('.')
  let val = tr[lang] || tr.en
  for (const k of keys) val = val?.[k]
  if (val === undefined) {
    // Фолбэк на английский по ключу, а не на сам ключ: недостающий
    // перевод должен выглядеть как английский текст, а не как products.rate
    let en = tr.en
    for (const k of keys) en = en?.[k]
    return en ?? key
  }
  return val
}
